"""The loanword table: spellings of one word folded to a canonical form.

A TSV beside the contract. Per entry: the canonical form; a pattern with an
alternation set at each differing position (ፕ[ሬረ][ዚዝዘ][ደዳ]ንት), everything it
generates being the same word; patterns for other lengths; the strict list,
the established spellings; and the tier the linguists assigned.

Two profiles, both recorded in every report: `lenient` folds anything a pattern
generates, `strict` the established spellings only.

Folding runs on whole tokens, both sides. An affixed form (በሚኒስተር) is not
folded; the substitutions it would match are counted under
`spelling_under_affix`.

The tier lookup serves the code-switching metrics: PIER is reported with and
without the points an established borrowing alone makes interesting.
"""

from __future__ import annotations

import csv
import hashlib
import itertools
import re
from dataclasses import dataclass
from pathlib import Path

PROFILES = ("lenient", "strict")
# Affixes admitted for the tier lookup and the under-affix flag only, never
# for folding.
_PREFIX = r"(?:እንደ|ስለ|ወደ|እና|የ|በ|ለ|ከ|ና)?(?:የ|በ|ለ|ከ)?"
_SUFFIX = r"[ችንምናውዎቹቻቸኝህሽስ]{0,4}"
_SLOT = re.compile(r"\[([^\]]+)\]|(.)")


def _slots(pattern: str) -> list[str]:
    return [a or b for a, b in _SLOT.findall(pattern)]


def _regex(pattern: str, *, fused_last: bool = False) -> str:
    slots = _slots(pattern)
    if fused_last and slots:
        # A suffix vowel fuses into a final consonant, the sixth-order letter
        # (ሪፖርት + ኡ = ሪፖርቱ), so under affixes that letter may take any order of
        # its row. A vowel-final letter keeps its order (ፖሊሲው): fusing it would
        # make ፖሊሲ match ፖሊሶች, the plural of ፖሊስ.
        slots = slots[:-1] + ["".join(sorted({o for c in slots[-1]
                                              for o in (_row(c) if _is_sixth(c) else c)}))]
    return "".join(f"[{re.escape(s)}]" if len(s) > 1 else re.escape(s) for s in slots)


def _is_sixth(ch: str) -> bool:
    """Whether `ch` is a sixth-order fidel (the consonant without a vowel, ስ ት ር)."""
    cp = ord(ch)
    return 0x1200 <= cp <= 0x137F and (cp - 0x1200) % 8 == 5


def _row(ch: str) -> str:
    cp = ord(ch)
    if not 0x1200 <= cp <= 0x137F:
        return ch
    base = cp - (cp - 0x1200) % 8
    return "".join(chr(base + k) for k in range(8))


def generate(pattern: str) -> list[str]:
    """Every form a pattern stands for."""
    return ["".join(p) for p in itertools.product(*_slots(pattern))]


@dataclass(frozen=True)
class Entry:
    word: str
    canonical: str
    patterns: tuple[str, ...]
    strict: frozenset[str]
    tier: str
    whole: re.Pattern
    affixed: re.Pattern
    affixed_plain: re.Pattern      # the same affixes, last letter not fused


class LoanwordTable:
    """The loaded table, with the folds and lookups the scorer needs."""

    def __init__(self, path: Path):
        self.path = path
        self.sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
        self.entries: list[Entry] = []
        with path.open(encoding="utf-8") as fh:
            rows = csv.DictReader((line for line in fh if not line.startswith("#")), delimiter="\t")
            for r in rows:
                patterns = tuple(p for p in [r["pattern"]] + r["alternative patterns"].split(" | ") if p)
                alternation = "|".join(_regex(p) for p in patterns)
                fused = "|".join(_regex(p, fused_last=True) for p in patterns)
                self.entries.append(Entry(
                    word=r["word"], canonical=r["canonical"], patterns=patterns,
                    # A multi-word entry's strict form stays whole: folding is per
                    # token, so splitting it would fold each word to the phrase.
                    strict=(frozenset(r["strict"].split()) if " " not in r["canonical"]
                            else frozenset(f.strip() for f in r["strict"].split("|") if f.strip())),
                    tier=r["tier"],
                    whole=re.compile(f"^(?:{alternation})$"),
                    affixed=re.compile(f"^{_PREFIX}({fused}){_SUFFIX}$"),
                    affixed_plain=re.compile(f"^{_PREFIX}({alternation}){_SUFFIX}$")))
        # Exact lookups for the common case; the regexes serve the rest. A form
        # two entries both generate would fold two words together; refuse it.
        self._lenient: dict[str, str] = {}
        for e in self.entries:
            for p in e.patterns:
                for form in generate(p):
                    if self._lenient.get(form, e.canonical) != e.canonical:
                        raise ValueError(f"{path}: {form} is generated by both {self._lenient[form]} and {e.canonical}")
                    self._lenient[form] = e.canonical
        # Same refusal for the strict list: a strict form claimed by two
        # entries, or one entry's strict form being another's canonical.
        self._strict: dict[str, str] = {}
        for e in self.entries:
            for form in e.strict:
                if self._strict.get(form, e.canonical) != e.canonical:
                    raise ValueError(f"{path}: strict form {form} belongs to both {self._strict[form]} and {e.canonical}")
                self._strict[form] = e.canonical
        for e in self.entries:
            if self._strict.get(e.canonical, e.canonical) != e.canonical:
                raise ValueError(f"{path}: {e.canonical} is canonical and a strict form of {self._strict[e.canonical]}")
            self._strict[e.canonical] = e.canonical

    def fold_token(self, token: str, profile: str) -> str:
        if profile == "lenient":
            return self._lenient.get(token, token)
        if profile == "strict":
            return self._strict.get(token, token)
        raise ValueError(f"profile must be one of {PROFILES}")

    def fold(self, text: str, profile: str) -> str:
        return " ".join(self.fold_token(t, profile) for t in text.split())

    def entry_of(self, token: str, *, affixed: bool = False) -> Entry | None:
        """The entry a token belongs to: bare, or under the known affixes."""
        canonical = self._lenient.get(token)
        if canonical is not None:
            return next(e for e in self.entries if e.canonical == canonical)
        if affixed:
            # An unfused match first (የፓርቲ is ፓርቲ, not ፓርት with a fused vowel).
            for attr in ("affixed_plain", "affixed"):
                for e in self.entries:
                    if getattr(e, attr).match(token):
                        return e
        return None

    def phrase_tiers(self, tokens: list[str]) -> dict[int, str]:
        """{token index: tier} for runs of `tokens` a multi-word entry covers.

        The joined window is matched against each multi-word entry's affixed
        pattern (የሶሻል ሚዲያው for ሶሻል ሚዲያ), longest entry first.
        """
        out: dict[int, str] = {}
        multi = sorted((e for e in self.entries if " " in e.canonical),
                       key=lambda e: len(e.canonical.split()), reverse=True)
        for e in multi:
            k = len(e.canonical.split())
            for i in range(len(tokens) - k + 1):
                if any(j in out for j in range(i, i + k)):
                    continue
                if e.affixed.match(" ".join(tokens[i:i + k])):
                    for j in range(i, i + k):
                        out[j] = e.tier
        return out

    def same_under_affix(self, ref: str, hyp: str) -> bool:
        """Two differing tokens that agree once a lenient fold is applied inside them.

        በሚኒስተር against በሚኒስቴር. Counted, not folded.
        """
        if ref == hyp:
            return False
        for e in self.entries:
            mr, mh = e.affixed.match(ref), e.affixed.match(hyp)
            if not (mr and mh):
                continue
            # same prefix, same suffix, and the same fused vowel on the stem's
            # last letter: only the spelling inside the stem may differ
            if (ref[:mr.start(1)] == hyp[:mh.start(1)] and ref[mr.end(1):] == hyp[mh.end(1):]
                    and mr.group(1)[-1] == mh.group(1)[-1]):
                return True
        return False


def load(path: Path) -> LoanwordTable:
    if not path.exists():
        raise FileNotFoundError(f"loanword table {path} not found")
    return LoanwordTable(path)
